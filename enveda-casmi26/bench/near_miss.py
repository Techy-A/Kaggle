"""Class-3 near-miss analysis: could engine 1's generator have produced the hidden answer, and from which parent?

For every class-3 molecule of a bench run:
  * oracle parents = the training structures (with spectra in the bench library) most similar to the answer
    (Morgan r2 2048 Tanimoto), i.e. the best parents a perfect analog search could pick;
  * reachable = engine 1's own rulebook (casmi.derive, <= 2 steps, same tolerance) turns one of the top-k oracle parents
    into the answer;
  * delta = formula difference answer - best oracle parent (what edit would be needed).
Splits the misses into 'parent selection' problems (reachable from an oracle parent, but engine 1 did not find it)
and 'rulebook gaps' (no oracle parent reaches it), with the most common missing formula deltas.

usage: python near_miss.py <run_dir> [top_k]
"""
import json
import os
import sys
from collections import Counter
from multiprocessing import Pool

import numpy as np
import pandas as pd

sys.path.insert(0, '/home/user/benchdata/v4b/code')
TS = '/home/user/benchdata/pool/train_structs.parquet'


def _fp(smi):
    from rdkit import Chem, RDLogger
    from rdkit.Chem import rdFingerprintGenerator
    RDLogger.DisableLog('rdApp.*')
    m = Chem.MolFromSmiles(smi) if isinstance(smi, str) else None
    if m is None:
        return None
    return rdFingerprintGenerator.GetMorganGenerator(radius=2, fpSize=2048).GetFingerprintAsNumPy(m).astype(np.uint8)


def formula_counts(f):
    import re
    c = Counter()
    for el, n in re.findall(r'([A-Z][a-z]?)(\d*)', f or ''):
        c[el] += int(n) if n else 1
    return c


def delta_str(fa, fb):
    a, b = formula_counts(fa), formula_counts(fb)
    d = {el: a[el] - b[el] for el in set(a) | set(b) if a[el] != b[el]}
    return ' '.join(f'{el}{v:+d}' for el, v in sorted(d.items())) or '0'


def _reach(task):
    from casmi import chem, derive
    akey, amass, parents = task
    for rank, (psmi, pmass) in enumerate(parents):
        try:
            prods = derive.derive(psmi, amass - pmass, tol=0.004, max_steps=2, max_per_analog=300)
        except Exception:
            continue
        for s in prods:
            std = chem.standardize_smiles(s)
            if std is not None and chem.score_key(std) == akey:
                return rank + 1
    return 0


def main(run, top_k=6):
    from casmi import chem
    ans = pd.read_csv(os.path.join(run, 'bench_answers.csv'), dtype=str, keep_default_na=False)
    ans['cls'] = ans.cls.astype(int)
    per = pd.read_csv(os.path.join(run, 'analysis_per_molecule.csv'))
    c3 = ans[ans.cls == 3].merge(per[['molecule_id', 'loss', 'in_final', 'in_base_tail', 'best_tc']], on='molecule_id')
    hidden = set(ans[ans.cls >= 2].inchikey14) | set(ans[ans.cls >= 2].metric_key)
    ts = pd.read_parquet(TS, columns=['inchikey14', 'smiles', 'formula', 'mass', 'key'])
    ts = ts[~ts.inchikey14.isin(hidden) & ~ts.key.isin(hidden)].reset_index(drop=True)
    with Pool(4) as p:
        fps = p.map(_fp, list(ts.smiles), chunksize=2000)
    ok = np.array([f is not None for f in fps])
    ts = ts[ok].reset_index(drop=True)
    F = np.stack([f for f in fps if f is not None]).astype(np.float32)
    nF = F.sum(1)
    print('library structures', len(ts), flush=True)
    tasks, rows = [], []
    for r in c3.itertuples():
        a = _fp(r.normalized_smiles)
        if a is None:
            continue
        a = a.astype(np.float32); inter = F @ a
        tc = inter / (nF + a.sum() - inter + 1e-9)
        top = np.argsort(-tc)[:top_k]
        props = chem.mol_props(chem.standardize_smiles(r.normalized_smiles) or r.normalized_smiles)
        amass = float(props[1]) if props else float('nan')
        aform = props[0] if props else ''
        tasks.append((r.metric_key, amass, [(ts.smiles[i], float(ts.mass[i])) for i in top]))
        rows.append(dict(molecule_id=r.molecule_id, loss=r.loss, in_final=r.in_final, engine1=r.in_base_tail,
                         oracle_tc=float(tc[top[0]]), oracle_delta=delta_str(aform, ts.formula[top[0]]),
                         d_mass=amass - float(ts.mass[top[0]])))
    with Pool(4) as p:
        reach = p.map(_reach, tasks, chunksize=1)
    df = pd.DataFrame(rows); df['reach_rank'] = reach
    df.to_csv(os.path.join(run, 'near_miss.csv'), index=False)
    found = df.engine1 > 0
    print(f'\nclass-3 molecules {len(df)} | engine 1 generated the answer for {int(found.sum())}')
    print(f'oracle parent Tc >= 0.7: {(df.oracle_tc >= 0.7).sum()} | answer reachable by the rulebook from a top-{top_k} oracle parent: {(df.reach_rank > 0).sum()}')
    miss = df[~found]
    print(f'\nNOT generated by engine 1: {len(miss)}')
    print(f'  reachable from an oracle parent (parent-selection problem): {(miss.reach_rank > 0).sum()}')
    print(f'  not reachable (rulebook gap or far parent): {(miss.reach_rank == 0).sum()}')
    gap = miss[miss.reach_rank == 0]
    print('  oracle Tc of the unreachable:', pd.cut(gap.oracle_tc, [0, .5, .6, .7, .8, .9, 1.0]).value_counts().sort_index().to_dict())
    print('  most common formula deltas (answer - best oracle parent) among unreachable with Tc >= 0.6:')
    for d, n in Counter(gap[gap.oracle_tc >= 0.6].oracle_delta).most_common(15):
        print(f'    {n:3d}  {d}')
    print('\nfound by engine 1 but not ranked first:', int((found & (df.in_final != 1)).sum()), '| ranked first:', int((df.in_final == 1).sum()))


if __name__ == '__main__':
    main(sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 6)
